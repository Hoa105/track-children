"""Generate reference-only Flutter constants from the approved v5.1 JSON."""
import json
from pathlib import Path


def main():
    mobile = Path(__file__).resolve().parents[1]
    source = mobile.parent / 'docs/update-teeth/01_DU_LIEU_2_TAB.json'
    data = json.loads(source.read_text(encoding='utf-8'))
    reference = data['reference_tab']
    stages = reference['stages']
    valid_codes = {str(pair[key]) for pair in data['tooth_pairs']
                   for key in ('fdi_right', 'fdi_left')}
    if len(stages) != 9 or [month for stage in stages
                           for month in range(stage['start_month'], stage['end_month'] + 1)] != list(range(61)):
        raise ValueError('Expected nine contiguous stages covering 0–60 months')
    quote = lambda value: json.dumps(str(value), ensure_ascii=False).replace('$', r'\$')
    lines = [
        '// GENERATED by tool/generate_teething_reference.py; do not edit.',
        '// Source: docs/update-teeth/01_DU_LIEU_2_TAB.json (reference_tab only).',
        "part of 'teething_reference_data.dart';", '',
        'const _referenceCountLabel = ' + quote(reference['ui_copy']['count_label_vi']) + ';',
        'const _referenceCountUnit = ' + quote(reference['ui_copy']['count_unit_vi']) + ';',
        'const _referenceStages = <TeethingReferenceStage>[',
    ]
    for stage in stages:
        codes = {str(code) for code in stage['highlight_fdi_codes']}
        if len(codes) != stage['possible_positions_count'] or not codes <= valid_codes:
            raise ValueError(f"Invalid FDI/count in {stage['stage_id']}")
        lines.extend([
            '  TeethingReferenceStage(',
            '    id: ' + quote(stage['stage_id']) + ',',
            f"    startMonth: {stage['start_month']}, endMonth: {stage['end_month']},",
            '    label: ' + quote(stage['label_vi']) + ',',
            f"    count: {stage['possible_positions_count']},",
            '    fdiCodes: <String>{' + ', '.join(quote(code) for code in stage['highlight_fdi_codes']) + '},',
            '    note: ' + quote(stage['note_vi']) + ',',
            *(['    noteTitle: ' + quote(stage['note_title_vi']) + ',']
              if stage.get('note_title_vi') else []),
            '  ),',
        ])
    lines.append('];')
    destination = mobile / 'lib/features/teething/teething_reference_stages.g.dart'
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Generated {len(stages)} reference stages; actual_tab unchanged.')


if __name__ == '__main__':
    main()
