"""Refresh the bundled CDC data embedded in migration 022."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.features.assessment.admin.transfer import bundled, normalize


def main():
    rows = bundled()
    _, errors = normalize(rows)
    if errors:
        raise ValueError(errors)
    payload = json.dumps(rows, ensure_ascii=False, indent=2)
    assert '$assessment_seed$' not in payload
    path = ROOT / 'migrations/022_assessment_sample_data.sql'
    text = path.read_text(encoding='utf-8')
    start = '-- BEGIN BUNDLED CDC DATA'
    end = '-- END BUNDLED CDC DATA'
    block = f'''{start}
-- Generated by backend/scripts/build_assessment_seed.py from bundled().
-- Includes the current enriched Vietnamese advice samples and source references.
-- Drafts only: publication and activation require the normal admin workflow.
CREATE TEMP TABLE assessment_seed_rows ON COMMIT DROP AS
SELECT * FROM jsonb_to_recordset($assessment_seed$
{payload}
$assessment_seed$::jsonb) AS seed(
    kind text, stable_code text, age_months smallint, set_code text,
    set_version text, locale text, set_source_name text, app_domain text,
    source_domain text, order_index integer, payload jsonb, source_refs jsonb
);

INSERT INTO assessment.question_sets
    (code, age_months, version, locale, source_name, status, is_active)
SELECT DISTINCT set_code, age_months, set_version, COALESCE(locale, 'vi-VN'),
    COALESCE(set_source_name, 'CDC Developmental Milestones'), 'draft', false
FROM assessment_seed_rows WHERE kind = 'skill'
ON CONFLICT (code) DO NOTHING;

INSERT INTO assessment.content_items
    (kind, stable_code, question_set_id, app_domain, source_domain, order_index,
     current_revision, is_active)
SELECT seed.kind, seed.stable_code, qs.id, seed.app_domain, seed.source_domain,
    seed.order_index, 1, false
FROM assessment_seed_rows seed
LEFT JOIN assessment.question_sets qs ON qs.code = seed.set_code
ON CONFLICT (kind, stable_code) DO NOTHING;

INSERT INTO assessment.content_revisions
    (content_item_id, revision, locale, payload, source_refs)
SELECT ci.id, 1, COALESCE(seed.locale, 'vi-VN'), seed.payload, seed.source_refs
FROM assessment_seed_rows seed
JOIN assessment.content_items ci
    ON ci.kind = seed.kind AND ci.stable_code = seed.stable_code
ON CONFLICT (content_item_id, revision) DO NOTHING;
{end}'''
    if start in text:
        text = text[:text.index(start)] + block + text[text.index(end) + len(end):]
    else:
        text = text.replace('COMMIT;', block + '\n\nCOMMIT;')
    text = text.replace('-- 022 - Local/demo data for the developmental assessment admin UI.',
                        '-- 022 - Assessment demo data, 12 CDC sets (159 skills), and 6 advice variants.')
    path.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
