"""Xuất lịch tiêm từ DB thành bản dự phòng offline cho mobile.

Chạy lại mỗi khi đổi seed lịch tiêm (migration) để app có lịch đúng khi chưa
kết nối được backend:

    python -m app.seed.export_mobile_schedule
"""

import json
from pathlib import Path

import psycopg2
from psycopg2.extras import RealDictCursor

from app.core.config import settings
from app.features.vaccination.schema import Schedule
from app.features.vaccination.service import get_schedule

TARGET = Path(__file__).resolve().parents[3] / "mobile/lib/services/vaccine_schedule_snapshot.dart"


def export() -> None:
    with psycopg2.connect(settings.database_url, cursor_factory=RealDictCursor) as conn:
        schedule = Schedule.model_validate(get_schedule(conn)).model_dump(mode="json", by_alias=True)
    payload = json.dumps(schedule, ensure_ascii=False, indent=1)
    TARGET.write_text(
        "// GENERATED by `python -m app.seed.export_mobile_schedule` (backend) — không sửa tay.\n"
        "// Bản dự phòng của GET /vaccines/schedule khi chưa kết nối được backend.\n"
        "const vaccineScheduleSnapshot = r'''\n" + payload + "\n''';\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Wrote {len(schedule['doses'])} doses, {len(schedule['vaccines'])} vaccines -> {TARGET}")


if __name__ == "__main__":
    export()
