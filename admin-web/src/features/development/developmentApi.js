import { adminRequest } from '../../core/http.js';
const base='/admin/development';
export const request=(admin,path,method='GET',body)=>adminRequest(admin,base+path,{method,body});
export const listQuestionSets=(a)=>request(a,'/question-sets');
export const getSet=(a,id)=>request(a,`/question-sets/${id}`);
export const createQuestionSet=(a,b)=>request(a,'/question-sets','POST',b);
export const updateQuestionSet=(a,id,b)=>request(a,`/question-sets/${id}`,'PATCH',b);
export const listContent=(a,id)=>request(a,`/question-sets/${id}/content?activeOnly=false`);
export const listAdvice=(a)=>request(a,'/content?kind=advice');
export const createContent=(a,id,b)=>request(a,`/question-sets/${id}/content`,'POST',b);
export const getContent=(a,id)=>request(a,`/content/${id}`);
export const listRevisions=(a,id)=>request(a,`/content/${id}/revisions`);
export const createRevision=(a,id,b)=>request(a,`/content/${id}/revisions`,'POST',b);
export const getGate=(a,id)=>request(a,`/content/${id}/gate`);
export const createReview=(a,id,b)=>request(a,`/content/${id}/reviews`,'POST',b);
export const publishContent=(a,id,v)=>request(a,`/content/${id}/publish`,'POST',{expectedRevision:v});
export const releaseContent=(a,id,v)=>request(a,`/content/${id}/release`,'POST',{expectedRevision:v});
export const publishQuestionSet=(a,id)=>request(a,`/question-sets/${id}/publish`,'POST');
export const releaseQuestionSet=(a,id)=>request(a,`/question-sets/${id}/release`,'POST');
export const lifecycle=(a,type,id,action,isActive)=>request(a,`/${type}/${id}${action==='delete'?'':`/${action}`}`,action==='delete'?'DELETE':action==='availability'?'PATCH':'POST',action==='availability'?{isActive}:undefined);
export const reorder=(a,id,contentIds)=>request(a,`/question-sets/${id}/order`,'PUT',{contentIds});
export const audit=(a,id)=>request(a,`/audit/${id}`);
export const exported=(a,setId,kind,setIds)=>{
 const query=new URLSearchParams({...setId&&{set_id:setId},...kind&&{kind}});
 setIds?.forEach(id=>query.append('set_ids',id));
 return request(a,`/export?${query}`);
};
export const importTemplate=(a,kind='skill')=>request(a,`/import/template?kind=${kind}`);
export const seedPreview=(a)=>request(a,'/seed-preview');
export const importPreview=(a,rows)=>request(a,'/import/preview','POST',{rows});
export const importCommit=(a,preview)=>request(a,'/import/commit','POST',{rows:preview.rows,fingerprint:preview.fingerprint});
export const reviewQueue=(a)=>request(a,'/review-queue');
